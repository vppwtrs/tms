-- ปิดสิทธิ์ที่หลุดไปกับ 20260827010000 — anon เรียกตัวคุมโควตาล็อกอินได้
--
-- ตรวจเจอจากภายนอกด้วย anon key ที่หยิบจาก bundle ของเว็บจริง:
--   POST /rest/v1/rpc/tms_login_gate  →  200 true
-- ทั้งที่ไฟล์ 20260827010000 เขียน `revoke all ... from public` ไว้แล้ว
--
-- ===== ทำไม revoke from public ถึงไม่พอ =====
-- Supabase ตั้ง default privileges ไว้ว่าฟังก์ชันใหม่ใน schema public ได้ execute
-- ให้ anon กับ authenticated **เป็นสิทธิ์ที่ให้ตรงตัว ไม่ได้ผ่าน PUBLIC**
-- การถอนจาก PUBLIC จึงไม่แตะสิทธิ์สองตัวนั้นเลย ต้องระบุชื่อบทบาทตรง ๆ
--
-- บทเรียนนี้กลับด้านกับที่จำกันมาว่า "ห้าม revoke from public เพราะตกถึง authenticated"
-- ของจริงคือ **ทั้งสองอย่างต้องทำ** และต้องพิสูจน์ด้วยการยิงจริงจากภายนอก
-- ไม่ใช่อ่านจากไฟล์ migration แล้วเชื่อว่าปิดแล้ว
--
-- ===== ความเสียหายถ้าไม่ปิด =====
-- tms_login_gate นับหนึ่งครั้งทุกครั้งที่ถูกเรียก คนนอกจึงยิงใส่ 'user:<ชื่อพนักงาน>'
-- รัว ๆ จนเต็มโควตา แล้วคนคนนั้นล็อกอินเข้าระบบไม่ได้ 15 นาที ทำวนไปเรื่อย ๆ ได้
-- = ปิดประตูใส่พนักงานตัวจริง ด้วยเครื่องมือที่เราสร้างมากันคนร้าย
--
-- tms_login_sweep หนักกว่า: ลบแถวใน tms_login_attempts (ล้างตัวนับทิ้ง = ตัวจำกัด
-- รอบเดารหัสหมดฤทธิ์) และลบ tms_sessions ที่หมดอายุ
--
-- ทั้งคู่ไม่มีหน้าจอไหนเรียก มีแต่ Edge Function ที่ใช้ service_role ซึ่งข้ามสิทธิ์อยู่แล้ว

revoke all on function public.tms_login_gate(text, int, interval) from anon, authenticated;
revoke all on function public.tms_login_sweep()                   from anon, authenticated;

/* ตารางนับก็หลุดมาด้วยเหตุผลเดียวกัน — ยิง REST ด้วย anon key แล้วได้ 200 []
   ตอนนี้ยังไม่รั่วเพราะ RLS เปิดและไม่มี policy สักอัน ทุกแถวจึงถูกกรองออกหมด
   แต่ grant ที่ค้างไว้แบบนี้คือระเบิดเวลา: วันไหนมีคนเพิ่ม policy เข้ามา
   มันจะกลายเป็นรูทันทีโดยไม่มีใครสังเกต เพราะ "ตารางนี้เคยเทสต์แล้วว่าอ่านไม่ได้"
   ปิดที่ชั้น grant ด้วย ไม่พึ่ง RLS ชั้นเดียว — เหมือนที่ tms_sessions ทำไว้ตั้งแต่แรก */
revoke all on table public.tms_login_attempts from anon, authenticated;
