-- ถัง pod-photos ยอมรับ WebP ด้วย
--
-- อาการ: คนขับที่ใช้เบราว์เซอร์ที่เข้ารหัส WebP ได้ (Chrome/Android ซึ่งคือเกือบทุกคน)
-- อัปโหลดรูปหลักฐานไม่ผ่าน ถังปฏิเสธตั้งแต่ชั้น storage ก่อนถึง RLS ด้วยซ้ำ
--
-- ต้นเหตุ: `allowed_mime_types` ของถังตั้งเป็น jpeg กับ png ตอนสร้างถัง แต่ตัวบีบรูป
-- เปลี่ยนไปคาย WebP แล้ว (web/src/utils/image.ts) ค่านี้ไม่เคยอยู่ใน migration ไหนเลย —
-- ถูกตั้งมือไว้ใน Dashboard ครั้งเดียวแล้วไม่มีใครเห็นมันอีก ซึ่งเป็นเหตุผลที่มันหลุด
-- ตอนแก้ฝั่งเว็บ และเป็นเหตุผลที่มันต้องอยู่ในไฟล์นี้ตั้งแต่แรก
--
-- png เก็บไว้ตามเดิม ลายเซ็นถูก render ออกมาจาก data URL เป็น PNG
--
-- ไม่แตะ public — ถังนี้ต้องเป็น private ตลอดไป ในนี้มีลายเซ็นลูกค้ากับหน้าร้าน
-- การอ่านผ่าน signed URL อายุจำกัดเท่านั้น

update storage.buckets
   set allowed_mime_types = array['image/jpeg', 'image/png', 'image/webp']
 where id = 'pod-photos';
